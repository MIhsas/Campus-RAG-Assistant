"""Health check endpoints.

GET /api/v1/health/live  — process liveness (always 200 if running)
GET /api/v1/health/ready — knowledge-base readiness (always 503 in T002/T003)

Request ID is generated by middleware and stored in request.state.request_id.
Routes read that value; they do not generate their own ID.
"""

from __future__ import annotations

from fastapi import APIRouter, Request

router = APIRouter(prefix="/api/v1/health", tags=["health"])

SERVICE_NAME = "campus-assistant-backend"
VERSION = "0.1.0"


@router.get("/live", status_code=200)
async def live(request: Request) -> dict:
    """Process is alive. No dependency on database, model, or knowledge base."""
    request_id = request.state.request_id
    return {
        "status": "ok",
        "service": SERVICE_NAME,
        "version": VERSION,
        "request_id": request_id,
    }


@router.get(
    "/ready",
    status_code=503,
    responses={
        503: {
            "description": "知识库尚未配置",
            "content": {
                "application/json": {
                    "example": {
                        "status": "not_ready",
                        "code": "KNOWLEDGE_BASE_NOT_CONFIGURED",
                        "message": "知识库尚未配置",
                        "retryable": False,
                        "request_id": "00000000-0000-0000-0000-000000000000",
                    }
                }
            },
        }
    },
)
async def ready(request: Request) -> dict:
    """Knowledge base readiness check. Fixed 503 in T002/T003."""
    request_id = request.state.request_id
    return {
        "status": "not_ready",
        "code": "KNOWLEDGE_BASE_NOT_CONFIGURED",
        "message": "知识库尚未配置",
        "retryable": False,
        "request_id": request_id,
    }
